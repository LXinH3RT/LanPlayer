def find_ffmpeg() -> Path:
    for candidate in (lp.TOOLS / "ffmpeg").rglob("ffmpeg.exe"):
        if candidate.is_file():
            return candidate
    raise lp.ScriptError("ffmpeg.exe not found - run: python tool/fetch_deps.py ffmpeg")


def srt(cues: list[tuple[str, str, str]]) -> str:
    lines: list[str] = []
    for index, (start, end, text) in enumerate(cues, start=1):
        lines += [str(index), f"{start} --> {end}", text, ""]
    return "\r\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out-dir", default="", help="output directory (default: build/doc-media)")
    args = parser.parse_args()

    out = Path(args.out_dir) if args.out_dir else lp.ROOT / "build" / "doc-media"
    ff = find_ffmpeg()

    if out.exists():
        import shutil
        shutil.rmtree(out)
    share = out / "share"

    def clip(path: Path, seconds: int = 3, size: str = "640x360") -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        lp.run([str(ff), "-hide_banner", "-loglevel", "error", "-y",
                "-f", "lavfi", "-i", f"testsrc2=size={size}:rate=25",
                "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=48000",
                "-t", str(seconds), "-c:v", "libx264", "-preset", "ultrafast",
                "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest", str(path)],
               show=False)

    # --- the share root: five folders, mirroring what the browser shows ------
    for name in ("downloads", "animation", "clips", "music", "movies"):
        (share / name).mkdir(parents=True, exist_ok=True)

    # --- a folder of .flv files plus one .docx -------------------------------
    # This is the "mixed folder" screenshot: the browser must hide the .docx and
    # keep the sixteen videos.
    clips = share / "clips"
    print(f"== {len(FLV_TITLES)} flv clips")
    for title in FLV_TITLES:
        clip(clips / title, seconds=2)
    # A document sitting next to the videos: proves the filter keeps it out.
    # The four bytes are the ZIP local-file header, which is all a file needs to
    # look like a .docx to a listing.
    (clips / "notes.docx").write_bytes(bytes([0x50, 0x4B, 0x03, 0x04]))

    # --- an anime folder: episodes with sidecar subtitles --------------------
    anime = share / "animation" / "anime-01"
    print("== anime-01 episodes + sidecars")
    for episode in range(1, 5):
        clip(anime / f"anime-01 - {episode:02d}.mkv", seconds=2)
        cues = [("00:00:00,500", "00:00:02,000", f"Episode {episode} (synthetic subtitle)")]
        (anime / f"anime-01 - {episode:02d}.zh.srt").write_text(srt(cues), encoding="utf-8", newline="")

    # --- two videos under movies --------------------------------------------
    clip(share / "movies" / "movie-01.mkv", seconds=4)
    clip(share / "movies" / "movie-02.mp4", seconds=4)

    # --- one video with an embedded subtitle and two sidecar files -----------
    # This is the subtitle-sheet screenshot: the sheet lists the embedded track
    # and both sidecars in one radio group, and the row that was picked has to
    # look picked.  The embedded track is muxed from a one-cue .srt; the two
    # sidecars are plain .ass files with ASCII names.
    print("== sidecar/embed.mkv + two .ass sidecars")
    sidecar = share / "sidecar"
    sidecar.mkdir(parents=True, exist_ok=True)
    srt_path = sidecar / "embedded.srt"
    srt_path.write_text(srt([("00:00:00,500", "00:00:28,000", "embedded subtitle track")]),
                        encoding="utf-8", newline="")
    lp.run([str(ff), "-hide_banner", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", "testsrc2=size=1280x720:rate=30:duration=30",
            "-f", "lavfi", "-i", "sine=frequency=440:duration=30",
            "-i", str(srt_path), "-map", "0:v", "-map", "1:a", "-map", "2:s",
            "-c:v", "libx264", "-preset", "veryfast", "-crf", "28", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-c:s", "srt",
            "-metadata:s:s:0", "language=eng", "-metadata:s:s:0", "title=Embedded",
            str(sidecar / "embed.mkv")], show=False)
    srt_path.unlink()

    for name in ("embed.ass", "embed.zh.ass"):
        lp.write_text(sidecar / name, ASS_TEMPLATE, newline="")

    # --- one video whose sidecar exercises the advanced ASS tags -------------
    # This is the "advanced tags" screenshot: a colour animation, a clip window,
    # karaoke fill, two vector drawings and one semi-transparent line, all in a
    # single file.  The picture underneath is a flat dark field so the caption
    # is the only thing on screen.
    print("== advanced/advanced.mkv + advanced.ass")
    advanced = share / "advanced"
    advanced.mkdir(parents=True, exist_ok=True)
    lp.run([str(ff), "-hide_banner", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", "color=c=0x202020:size=1280x720:rate=24:duration=20",
            "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=48000:duration=20",
            "-c:v", "libx264", "-preset", "veryfast", "-crf", "30",
            "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest",
            str(advanced / "advanced.mkv")], show=False)
    lp.write_text(advanced / "advanced.ass", ADVANCED_ASS_TEMPLATE, newline="")

    print(f"== doc media built at {out}")
    counts: dict[str, int] = {}
    for path in out.rglob("*"):
        if path.is_file():
            counts[path.suffix or "(none)"] = counts.get(path.suffix or "(none)", 0) + 1
    for suffix, count in sorted(counts.items()):
        print(f"   {suffix} {count} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(lp.main(main))
