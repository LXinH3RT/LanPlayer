#!/usr/bin/env python3
"""Build a privacy-free fixture tree used only for taking documentation screenshots.

Everything under the output directory is synthetic: generated by FFmpeg's lavfi
sources, with neutral file names.  Nothing here comes from a real share, so the
resulting screenshots can be published as-is.

    python scripts/make_doc_media.py
"""
